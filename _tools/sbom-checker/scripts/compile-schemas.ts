/**
 * Compiles the vendored CycloneDX and SPDX JSON schemas into standalone
 * validator modules (src/schema/generated/*.js).
 *
 * Compiling at build time means the browser never runs Ajv's compiler: no
 * `new Function`, so the page works under a strict CSP, and each schema
 * ships as plain code that is loaded only when a document of that version
 * is checked.
 */
import Ajv from "ajv";
import Ajv2020 from "ajv/dist/2020";
import standaloneCode from "ajv/dist/standalone";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { _ } from "ajv";
import { SCHEMAS } from "../src/schema/catalogue";
import { formats } from "../src/schema/formats";

const root = join(import.meta.dir, "..");
const schemaDir = join(root, "schemas");
const outDir = join(root, "src", "schema", "generated");
mkdirSync(outDir, { recursive: true });

const load = (file: string) => stripAnnotations(JSON.parse(readFileSync(join(schemaDir, file), "utf8"))) as Record<string, unknown>;

// Annotation keywords do not affect validation, but Ajv embeds the schema
// in the generated code, so dropping them roughly halves each validator.
const ANNOTATIONS = new Set(["description", "title", "examples", "$comment", "meta:enum", "deprecated", "default"]);
// Keywords whose value is a map of names to subschemas: the keys there are
// property names (a CycloneDX component has a "description" property), not
// keywords, so they must be kept.
const SCHEMA_MAPS = new Set(["properties", "patternProperties", "definitions", "$defs", "dependentSchemas"]);

function stripAnnotations(node: unknown): unknown {
  if (Array.isArray(node)) return node.map(stripAnnotations);
  if (node === null || typeof node !== "object") return node;
  const out: Record<string, unknown> = {};
  for (const [key, value] of Object.entries(node)) {
    if (ANNOTATIONS.has(key)) continue;
    if (SCHEMA_MAPS.has(key) && value && typeof value === "object" && !Array.isArray(value)) {
      out[key] = Object.fromEntries(Object.entries(value).map(([k, v]) => [k, stripAnnotations(v)]));
    } else if (key === "enum" || key === "const" || key === "required") {
      out[key] = value;
    } else {
      out[key] = stripAnnotations(value);
    }
  }
  return out;
}


function makeAjv(draft2020: boolean) {
  const options = {
    strict: false,
    allErrors: true,
    // Up to this many errors per document; enough to explain, not to drown.
    code: { source: true, esm: true, optimize: true, formats: _`require("../formats").formats` },
  } as const;
  const ajv = draft2020 ? new Ajv2020(options) : new Ajv(options);
  for (const [name, fn] of Object.entries(formats)) ajv.addFormat(name, fn as (s: string) => boolean);
  return ajv;
}

const cdxShared = ["spdx.schema.json", "jsf-0.82.schema.json", "cryptography-defs.schema.json"];

for (const entry of SCHEMAS) {
  const ajv = makeAjv(entry.draft2020);
  if (entry.format === "cyclonedx") for (const f of cdxShared) ajv.addSchema(load(f));
  const validate = ajv.compile(load(entry.file));
  let code = standaloneCode(ajv, validate);
  // Ajv emits CommonJS `require` for formats and runtime helpers even in ESM
  // mode; rewrite to imports so the bundler can split each validator into
  // its own chunk.
  const imports: string[] = [];
  let n = 0;
  code = code.replace(/require\("([^"]+)"\)/g, (_m, spec: string) => {
    const name = `__req${n++}`;
        // Ajv's runtime helpers are CommonJS (`exports.default = fn`). Bundlers
    // disagree on how a namespace import of that looks, so normalise to an
    // object whose `.default` is the function, which is what the code expects.
    imports.push(
      spec.startsWith(".")
        ? `import * as ${name} from ${JSON.stringify(spec)};`
        : `import * as ${name}_ns from ${JSON.stringify(spec)};\nconst ${name} = typeof ${name}_ns.default === "function" ? ${name}_ns : ${name}_ns.default;`,
    );
    return name;
  });
  writeFileSync(join(outDir, `${entry.id}.js`), `// @ts-nocheck\n// Generated by scripts/compile-schemas.ts from schemas/${entry.file}. Do not edit.\n${imports.join("\n")}\n${code}`);
  writeFileSync(
    join(outDir, `${entry.id}.d.ts`),
    `// Generated by scripts/compile-schemas.ts. Do not edit.\nimport type { ValidateFunction } from "ajv";\nexport declare const validate: ValidateFunction;\nexport default validate;\n`,
  );
  console.log(`compiled ${entry.file} -> generated/${entry.id}.js (${(code.length / 1024).toFixed(0)} KiB)`);
}
